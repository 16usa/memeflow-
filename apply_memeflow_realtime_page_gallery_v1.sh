#!/usr/bin/env bash
set -Eeuo pipefail

PATCH_ID="MEMEFLOW_REALTIME_PAGE_GALLERY_V1"
COMMIT_MESSAGE="Replace architecture 3D with interactive page gallery"
DO_PUSH=1

for arg in "$@"; do
  case "$arg" in
    --push) DO_PUSH=1 ;;
    --no-push) DO_PUSH=0 ;;
    *)
      echo "Usage: $0 [--push|--no-push]" >&2
      exit 2
      ;;
  esac
done

ROOT="$(git rev-parse --show-toplevel 2>/dev/null || true)"
if [[ -z "$ROOT" ]]; then
  echo "ERROR: run this patch inside the MEMEFLOW git repository." >&2
  exit 1
fi

if [[ -d "$ROOT/memeflow-app" ]]; then
  APP="$ROOT/memeflow-app"
elif [[ -f "$ROOT/system.html" ]]; then
  APP="$ROOT"
else
  echo "ERROR: could not locate memeflow-app/system.html." >&2
  exit 1
fi

HTML="$APP/system.html"
CSS="$APP/system.css"
JS="$APP/system.js"
TRADING="$APP/trading.html"
TOKENS="$APP/system-tokens.html"
ASSET_DIR="$APP/memeflow-gallery"

for f in "$HTML" "$CSS" "$JS" "$TRADING" "$TOKENS"; do
  [[ -f "$f" ]] || {
    echo "ERROR: required file missing: $f" >&2
    exit 1
  }
done

echo
echo "MEMEFLOW Real-Time Architecture page gallery V1"
echo "App: $APP"

grep -Fq "Live MEMEFLOW pipeline" "$HTML" || {
  echo "ERROR: system.html is not the expected Real-Time Architecture page." >&2
  exit 1
}
grep -Fq "viewport-wrap" "$HTML" || {
  echo "ERROR: 3D viewport anchor .viewport-wrap was not found." >&2
  exit 1
}

OWNED_EXISTING=("$HTML" "$CSS" "$JS")
for f in "${OWNED_EXISTING[@]}"; do
  rel="${f#"$ROOT"/}"
  if ! git -C "$ROOT" diff --quiet -- "$rel" || \
     ! git -C "$ROOT" diff --cached --quiet -- "$rel"; then
    echo "ERROR: target file already has local/staged edits: $rel" >&2
    echo "Commit/stash that target file first. Nothing was changed." >&2
    exit 1
  fi
done

BRANCH="$(git -C "$ROOT" branch --show-current)"
if [[ -z "$BRANCH" ]]; then
  echo "ERROR: detached HEAD; switch to the active branch first." >&2
  exit 1
fi

if [[ "$DO_PUSH" == "1" ]]; then
  git -C "$ROOT" fetch origin "$BRANCH"
  LOCAL_HEAD="$(git -C "$ROOT" rev-parse HEAD)"
  REMOTE_HEAD="$(git -C "$ROOT" rev-parse "origin/$BRANCH")"
  if [[ "$LOCAL_HEAD" != "$REMOTE_HEAD" ]]; then
    echo "ERROR: local $BRANCH is not identical to origin/$BRANCH." >&2
    echo "Local : $LOCAL_HEAD" >&2
    echo "Remote: $REMOTE_HEAD" >&2
    echo "Nothing was changed. Sync the branch first." >&2
    exit 1
  fi
fi

if grep -Fq "$PATCH_ID" "$CSS" && grep -Fq "$PATCH_ID" "$JS"; then
  echo "Already installed: $PATCH_ID"
  exit 0
fi

STAMP="$(date +%Y%m%d-%H%M%S)"
BACKUP="$ROOT/.patch-backups/realtime-page-gallery-v1-$STAMP"
mkdir -p "$BACKUP"
cp -p "$HTML" "$CSS" "$JS" "$BACKUP"/
[[ -d "$ASSET_DIR" ]] && cp -a "$ASSET_DIR" "$BACKUP/memeflow-gallery-existing" || true

restore_on_error() {
  local rc=$?
  if [[ $rc -ne 0 ]]; then
    echo
    echo "Patch failed; restoring exact pre-patch files..."
    cp -p "$BACKUP/system.html" "$HTML"
    cp -p "$BACKUP/system.css" "$CSS"
    cp -p "$BACKUP/system.js" "$JS"
    rm -rf "$ASSET_DIR"
    if [[ -d "$BACKUP/memeflow-gallery-existing" ]]; then
      cp -a "$BACKUP/memeflow-gallery-existing" "$ASSET_DIR"
    fi
    echo "Rollback complete."
  fi
  exit "$rc"
}
trap restore_on_error EXIT

