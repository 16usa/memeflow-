import assert from 'node:assert/strict';
import {quantumDecision} from '../src/quantum-decision-engine.mjs';
import {resolveQuantumPattern} from '../src/quantum-pattern-provider.mjs';
const now=Date.now();
const token={priceSol:0.00001,holderCount:120,top10Pct:10,developerPct:2,buyPressure:70,suspectedRiskyWalletsPct:5,insidersPct:3};
const ready={shadowTokenPattern:{ready:true,patternProbabilityPositivePct:90,matchConfidencePct:90}};
const bearish={shadowTokenPattern:{ready:true,patternProbabilityPositivePct:20,matchConfidencePct:90}};
const cold={shadowTokenPattern:{ready:false}};
const score=quantumDecision(token,{},ready);
assert.equal(score.state,'BUY READY');
assert.equal(score.scoreAuthority,'quantum-decision-engine');
assert.equal(quantumDecision({...token,dead:true},{},ready).state,'BLOCKED');
assert.equal(quantumDecision({...token,priceSol:null},{},ready).state,'WAITING');
assert.equal(quantumDecision(token,{},bearish).state,'WATCH');
assert.equal(quantumDecision(token,{},cold).state,'WAITING');
assert.equal(quantumDecision({...token,suspectedRiskyWalletsPct:99},{maxSuspectedRiskyWalletsPct:20},{...ready,__quantumPreOpen:true}).state,'BLOCKED');
const cell=(at)=>({snapshot:{observedAt:at,shadowTokenPattern:{ready:true,patternProbabilityPositivePct:90,matchConfidencePct:90}}});
assert.equal(resolveQuantumPattern(cell(now),{now}).shadowTokenPattern.ready,true);
assert.equal(resolveQuantumPattern(cell(now-180000),{now}).shadowTokenPattern.ready,false);
assert.equal(resolveQuantumPattern({snapshot:{shadowTokenPattern:ready.shadowTokenPattern}},{now}).shadowTokenPattern.ready,false);
console.log('Quantum Stage 6 regression tests passed (simulation only)');
