import assert from 'node:assert/strict';
import {validateMomentum} from '../scripts/quantum-stage37-momentum-validation.mjs';
const row=(mint,acc,ret,status='MATURED')=>({mint,quantumState:'CANDIDATE',horizonMin:5,status,returnPct:ret,preEntry:acc===null?{status:'OBSERVED',accelerationPct:null}:{status:'OBSERVED',accelerationPct:acc}});
const r=validateMomentum([row('a',5,-10),row('b',25,20),row('c',35,-5),row('d',null,3),row('e',40,null,'MISSING_FOLLOWUP'),{...row('x',50,5),quantumState:'WATCH'}]);
assert.equal(r.tradeAuthority,false);
assert.equal(r.validated,false);
assert.equal(r.thresholdsChanged,false);
assert.equal(r.candidateCohort,5);
assert.equal(r.matured.count,4);
assert.equal(r.withAcceleration.count,3);
assert.equal(r.withoutAcceleration.count,1);
assert.equal(r.missingFollowup,1);
assert.equal(r.scenarios.length,5);
assert.equal(r.scenarios[0].pass.count,3);
assert.equal(r.scenarios[1].pass.count,2);
assert.equal(r.scenarios[2].fail.count,1);
assert.equal(r.scenarios[3].pass.count,1);
assert.equal(r.scenarios[4].pass.count,0);
assert.deepEqual(r.scenarios[4].leaveOneOutMeanRange,null);
assert.deepEqual(r.scenarios[1].leaveOneOutMeanRange,[-5,20]);
console.log('Stage 37 tests passed (15 assertions)');
