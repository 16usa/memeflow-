import assert from 'node:assert/strict';
import {analyze} from '../scripts/quantum-stage31-report.mjs';
const t=1_800_000_000_000;
const e=(mint,state,legacy='WATCH')=>({version:25,mint,at:t,priceAt:t,priceSol:1,state:legacy,stage29ShadowDecision:{state}});
const p=(mint,delta,price)=>({mint,priceAt:t+delta,priceSol:price});
const out=analyze([e('a','CANDIDATE','BUY READY'),e('b','BLOCKED'),e('c','WATCH'),{...e('a','CANDIDATE'),at:t+2000,priceAt:t+2000,priceSol:2}], [p('a',300000,1.1),p('b',300000,0.8),p('c',300000-1,5)],t+480000);
assert.equal(out.decisions,3);
assert.equal(out.groups[5].all.matured,2);
assert.equal(out.groups[5].all.missingFollowup,1);
assert.equal(out.groups[5].byQuantum.CANDIDATE.meanReturnPct,10);
assert.equal(out.groups[5].byQuantum.BLOCKED.meanReturnPct,-20);
assert.equal(out.groups[5].pairedBuyReadyCandidate.matured,1);
assert.equal(out.groups[5].pairedBuyReadyNotCandidate.cohort,0);
assert.equal(out.groups[15].all.pending,3);
assert.equal(out.groups[5].all.coveragePct,66.67);
assert.equal(out.groups[5].all.windowOpen,0);
const journal=analyze([e('j','WATCH'),{mint:'j',at:t+300001,priceAt:t+300001,priceSol:1.5}],[],t+500000);
assert.equal(journal.groups[5].all.matured,1);
assert.equal(journal.groups[5].all.meanReturnPct,50);
const noFuture=analyze([e('z','WAITING'),{mint:'z',at:t+300001,priceAt:t+400000,priceSol:3}],[],t+500000);
assert.equal(noFuture.groups[5].all.matured,0);
const late=analyze([e('x','WAITING')],[p('x',420001,2)],t+500000);
assert.equal(late.groups[5].all.matured,0);
const open=analyze([e('y','WATCH')],[],t+360000);
assert.equal(open.groups[5].all.windowOpen,1);
console.log('Stage 31 tests passed (15 assertions)');
