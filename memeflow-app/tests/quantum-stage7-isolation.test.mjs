import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {quantumDecision} from '../src/quantum-decision-engine.mjs';
import {resolveQuantumPattern} from '../src/quantum-pattern-provider.mjs';
const src=readFileSync(new URL('../app-server.mjs',import.meta.url),'utf8');
assert.match(src,/MEMEFLOW_QUANTUM_STAGE7_LEGACY_BRIDGE_ISOLATION/);
assert.match(src,/scoreAuthority\|\|''\)===\s*'quantum-decision-engine'\) return decision/);
const token={mint:'test',priceSol:0.00001,holderCount:150,top10Pct:10,developerPct:2,buyPressure:100};
const pattern={shadowTokenPattern:{ready:true,patternProbabilityPositivePct:90,matchConfidencePct:90}};
const ready=quantumDecision(token,{},pattern);
assert.equal(ready.scoreAuthority,'quantum-decision-engine');
assert.equal(ready.state,'BUY READY');
assert.equal(quantumDecision({...token,dead:true},{},pattern).state,'BLOCKED');
assert.equal(quantumDecision(token,{},{}).state,'WAITING');
const stale=resolveQuantumPattern({snapshot:{observedAt:Date.now()-500000,shadowTokenPattern:{ready:true,patternProbabilityPositivePct:90,matchConfidencePct:90}}});
assert.equal(stale.shadowTokenPattern.ready,false);
const blocked=quantumDecision({...token,suspectedRiskyWalletsPct:60},{maxSuspectedRiskyWalletsPct:40},{...pattern,__quantumPreOpen:true});
assert.equal(blocked.state,'BLOCKED');
console.log('Quantum Stage 7 isolation tests passed (static + unit; not live execution)');
