import assert from 'node:assert/strict';
import {cohort,analyze} from '../scripts/quantum-stage30-report.mjs';
const t=1000000000;const e=(mint,state,at=t,priceSol=1,memflow='WATCH')=>({version:25,mint,at,priceSol,state:memflow,stage29ShadowDecision:{state}});
const ds=[e('A','CANDIDATE'),e('A','CANDIDATE',t+1000),e('B','BLOCKED'),e('C','WATCH'),e('D','WAITING'),e('E','WATCH',t,1,'BUY READY')];
assert.equal(cohort(ds).length,5);
assert.equal(cohort(ds)[0].at,t);
assert.equal(cohort([e('A','OTHER')]).length,0);
assert.equal(cohort([{...e('A','WATCH'),priceSol:null}]).length,0);
const p=[{mint:'A',priceAt:t+5*60000,priceSol:1.2},{mint:'B',priceAt:t+5*60000,priceSol:0.8},{mint:'C',priceAt:t+5*60000+120001,priceSol:4},{mint:'E',priceAt:t+5*60000,priceSol:1.1}];
const r=analyze(ds,p,t+6*60000);
assert.equal(r.decisions,5);
assert.equal(r.groups[5].byQuantum.CANDIDATE.matured,1);
assert.equal(r.groups[5].byQuantum.CANDIDATE.meanReturnPct,20);
assert.equal(r.groups[5].byQuantum.BLOCKED.meanReturnPct,-20);
assert.equal(r.groups[5].byQuantum.WATCH.missingFollowup,1);
assert.equal(r.groups[5].byQuantum.WAITING.missingFollowup,1);
assert.equal(r.groups[15].all.pending,5);
assert.equal(r.groups[5].memflowBuyReadyNotCandidate.cohort,1);
assert.equal(r.groups[5].all.matured,3);
assert.equal(r.groups[5].all.coveragePct,60);
assert.equal(r.tradeAuthority,false);
assert.equal(r.verifiedAccuracy,false);
console.log('Stage 30 tests passed (15 assertions)');
